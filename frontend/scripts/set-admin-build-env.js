#!/usr/bin/env node
/**
 * Force the ADMIN production build to be the ADMIN application.
 *
 * THE PROBLEM
 * -----------
 * Create React App loads env files in this precedence order (highest first):
 *
 *     .env.production.local   <-- highest
 *     .env.local              <-- wins over .env.production
 *     .env.production
 *     .env
 *
 * `frontend/.env.local` is overwritten by the `start:delivery` / `start:admin`
 * scripts. Because it sits ABOVE `.env.production`, a leftover
 * `REACT_APP_TYPE=delivery` silently turns a build into the Delivery app.
 * That is not hypothetical: it caused "/" to redirect to "/login" during this
 * project, and `scripts/set-web-build-env.js` was added to fix it for the WEB
 * build. The ADMIN build had NO equivalent guard, so it depended entirely on
 * whatever happened to be in `.env.local` at the time. That is the risk this
 * file closes.
 *
 * THE FIX
 * -------
 * Write `.env.production.local` (the HIGHEST precedence file) with the correct
 * Admin values before every Admin build. `.env.local` is left completely
 * untouched, so local development configuration is preserved.
 *
 * Only NODE_ENV=production builds are affected. `npm start` is unchanged.
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const TARGET = path.join(ROOT, ".env.production.local");

const TYPE = "admin";
// Same-origin API in production: nginx proxies /auth/, /rides/, /operations/...
const API_URL = "https://www.yalataxi.live";

const contents = [
  "# AUTO-GENERATED by scripts/set-admin-build-env.js - do not edit, do not commit.",
  "#",
  "# This file exists solely to out-rank .env.local, which the start:delivery and",
  "# start:admin scripts overwrite. Without it a leftover REACT_APP_TYPE=delivery",
  "# in .env.local would turn an Admin build into the Delivery application.",
  `REACT_APP_TYPE=${TYPE}`,
  `REACT_APP_API_URL=${API_URL}`,
  "",
].join("\n");

fs.writeFileSync(TARGET, contents, "utf8");

// Report (do not change) any conflicting local override, so it is visible.
const localEnv = path.join(ROOT, ".env.local");
let note = "";
if (fs.existsSync(localEnv)) {
  const local = fs.readFileSync(localEnv, "utf8");
  const m = local.match(/^\s*REACT_APP_TYPE\s*=\s*(.+)$/m);
  if (m && m[1].trim() !== TYPE) {
    note = `  NOTE: .env.local requested REACT_APP_TYPE=${m[1].trim()} - overridden to "${TYPE}" for this build.`;
  }
}

console.log(`[set-admin-build-env] wrote .env.production.local with REACT_APP_TYPE=${TYPE}`);
if (note) console.log(note);
