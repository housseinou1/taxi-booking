#!/usr/bin/env node
/**
 * Force production builds to be the WEB application.
 *
 * THE PROBLEM
 * -----------
 * Create React App loads env files in this precedence order (highest first):
 *
 *     .env.production.local
 *     .env.local            <-- wins over .env.production
 *     .env.production
 *     .env
 *
 * `frontend/.env.local` is written by the `start:delivery` / `start:admin`
 * scripts. Because it sits ABOVE `.env.production`, a leftover
 * `REACT_APP_TYPE=delivery` silently turns a production build into the
 * Delivery app. That is not hypothetical: it caused "/" to redirect to
 * "/login" during this project, and it would have shipped the wrong
 * application to the public web.
 *
 * THE FIX
 * -------
 * Write `.env.production.local` (the HIGHEST precedence file) with
 * REACT_APP_TYPE=web before every build. `.env.local` is left completely
 * untouched, so local development configuration is preserved.
 *
 * Only NODE_ENV=production builds are affected. `npm start` is unchanged.
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const TARGET = path.join(ROOT, ".env.production.local");

const isProductionBuild = true; // this script is only ever run by the `build` script

if (!isProductionBuild) {
  console.log("[set-web-build-env] not a production build - no changes");
  process.exit(0);
}

const lines = [
  "# AUTO-GENERATED by scripts/set-web-build-env.js - do not edit, do not commit.",
  "#",
  "# This file exists solely to out-rank .env.local, which the start:delivery and",
  "# start:admin scripts overwrite. Without it a leftover REACT_APP_TYPE=delivery",
  "# in .env.local would turn a production build into the Delivery application.",
  "REACT_APP_TYPE=web",
];
if (process.env.REACT_APP_PROD_LEGACY_BACKEND === "1") {
  lines.push(
    "# Frontend-only cut against production API without Moosyl / ID-card routes.",
    "REACT_APP_MOOSYL_UI_ENABLED=0",
    "REACT_APP_ID_CARD_ADMIN_UI_ENABLED=0"
  );
}
const contents = `${lines.join("\n")}\n`;

fs.writeFileSync(TARGET, contents, "utf8");

const localEnv = path.join(ROOT, ".env.local");
let note = "";
if (fs.existsSync(localEnv)) {
  const local = fs.readFileSync(localEnv, "utf8");
  const m = local.match(/^\s*REACT_APP_TYPE\s*=\s*(.+)$/m);
  if (m && m[1].trim() !== "web") {
    note = `  NOTE: .env.local requested REACT_APP_TYPE=${m[1].trim()} - overridden to "web" for this build.`;
  }
}

console.log("[set-web-build-env] wrote .env.production.local with REACT_APP_TYPE=web");
if (note) console.log(note);
